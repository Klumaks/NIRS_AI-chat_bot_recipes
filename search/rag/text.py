class Normalizer:
    """Приведение слова к нормальной форме.

    mode:
        "lemma" — лемматизация pymorphy3 (по умолчанию);
        "stem"  — стеммер Портера (без внешних зависимостей);
        "none"  — без нормализации (только нижний регистр).
    Если выбран "lemma", но pymorphy3 не установлен, используется "stem".
    """

    def __init__(self, mode: str = "lemma"):
        if mode not in {"lemma", "stem", "none"}:
            raise ValueError(f"unknown mode: {mode}")
        self._morph = None
        if mode == "lemma":
            try:
                import pymorphy3  # type: ignore

                self._morph = pymorphy3.MorphAnalyzer()
            except ImportError:
                mode = "stem"
        self.mode = mode
        self._cache: dict[str, str] = {}
        if mode == "stem":
            # Для стеммера переводим словарь синонимов в основы.
            self._synonyms = {_porter_stem(k): _porter_stem(v) for k, v in SYNONYMS_LEMMA.items()}
            self._stop = {_porter_stem(w) for w in STOPWORDS} | STOPWORDS
        else:
            self._synonyms = SYNONYMS_LEMMA
            self._stop = STOPWORDS

    def word(self, w: str) -> str:
        cached = self._cache.get(w)
        if cached is not None:
            return cached
        if self.mode == "lemma":
            norm = self._morph.parse(w)[0].normal_form.replace("ё", "е")
        elif self.mode == "stem":
            norm = _porter_stem(w)
        else:
            norm = w
        norm = self._synonyms.get(norm, norm)
        self._cache[w] = norm
        return norm

    def tokens(self, text: str) -> list[str]:
        """Полный конвейер предобработки: текст -> список термов."""
        text = text.lower().replace("ё", "е")
        out = []
        for tok in TOKEN_RE.findall(text):
            if len(tok) < MIN_TOKEN_LEN or tok in STOPWORDS:
                continue
            norm = self.word(tok)
            if norm in self._stop or len(norm) < MIN_TOKEN_LEN:
                continue
            out.append(norm)
        return out


@lru_cache(maxsize=4)
def get_normalizer(mode: str = "lemma") -> Normalizer:
    return Normalizer(mode)
